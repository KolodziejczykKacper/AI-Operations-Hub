"""Excel export of approved cases.

The workbook is generated by the API only when the user clicks the button; the bytes are kept
in the session so that Streamlit reruns (and the download click itself) never call the API again.
The screen only reports that the file is READY: it can not know whether it was downloaded.
"""

from __future__ import annotations

from datetime import date, datetime

import streamlit as st

from ai_ops_hub.ui.client import XLSX_MIME, ApiClient, ApiError, BackendUnavailable, ClientError
from ai_ops_hub.ui.common import call
from ai_ops_hub.ui.models import ExportSummary
from ai_ops_hub.ui.safe import esc

_FILTER_ERRORS = {"invalid_export_filter", "validation_error"}


def cases_pl(n: int) -> str:
    """'1 przypadek', '2 przypadki', '5 przypadków' (Polish plural forms)."""
    if n == 1:
        return "1 przypadek"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f"{n} przypadki"
    return f"{n} przypadków"


def _summary(client: ApiClient, approved_from: date | None, approved_to: date | None) -> ExportSummary | str:
    """The summary, or a user-facing message when the filter itself is refused."""
    try:
        return client.export_summary(approved_from=approved_from, approved_to=approved_to)
    except ApiError as exc:
        if exc.code in _FILTER_ERRORS:
            return f"Nieprawidłowy zakres dat: {exc.message}"
        raise


def _explain(exc: ClientError) -> tuple[str, str]:
    """(level, message) for a failed generation."""
    if isinstance(exc, ApiError):
        if exc.code == "no_approved_cases":
            return "warning", "Brak zatwierdzonych przypadków do wyeksportowania (dla wybranego zakresu)."
        if exc.code == "export_too_large":
            return "error", f"Za dużo przypadków na jeden plik. Zawęź zakres dat zatwierdzenia. ({esc(exc.message)})"
        if exc.code in _FILTER_ERRORS:
            return "error", f"Nieprawidłowy zakres dat: {esc(exc.message)}"
        return "error", f"Nie udało się wygenerować pliku ({esc(exc.code)}): {esc(exc.message)}"
    if isinstance(exc, BackendUnavailable):
        return "error", f"Nie udało się połączyć z API: {esc(exc)}"
    return "error", f"Nie udało się wygenerować pliku: {esc(exc)}"


def _generate(client: ApiClient, approved_from: date | None, approved_to: date | None) -> None:
    ss = st.session_state
    ss.pop("x_error", None)
    try:
        file = client.export_approved_cases(approved_from=approved_from, approved_to=approved_to)
    except ClientError as exc:
        ss.pop("x_result", None)
        ss["x_error"] = _explain(exc)
        return
    ss["x_result"] = {
        "file": file,
        "filters": (approved_from, approved_to),
        "generated_at": datetime.now(),
    }


def render(client: ApiClient) -> None:
    ss = st.session_state
    st.header("Eksport do Excela")
    st.write(
        "Plik zawiera **tylko zatwierdzone** przypadki, z danymi zatwierdzonymi przez człowieka "
        "(poprawki mają pierwszeństwo przed wynikiem analizy regułowej). Odrzucone, otwarte i "
        "ponownie otwarte przypadki oraz konfliktowe wiadomości nie są eksportowane. "
        "Eksport niczego nie zmienia i niczego nie wysyła."
    )

    ss.setdefault("x_use_range", False)
    st.checkbox("Ogranicz do zakresu dat zatwierdzenia (UTC)", key="x_use_range")
    approved_from = approved_to = None
    if ss["x_use_range"]:
        c1, c2 = st.columns(2)
        ss.setdefault("x_from", date.today())
        ss.setdefault("x_to", date.today())
        approved_from = c1.date_input("Od dnia (włącznie)", key="x_from")
        approved_to = c2.date_input("Do dnia (włącznie)", key="x_to")

    summary = call(_summary, client, approved_from, approved_to)
    if isinstance(summary, str):
        st.error(esc(summary))
        return

    st.metric("Zatwierdzone przypadki gotowe do eksportu", summary.eligible_count)
    if summary.skipped_count:
        st.warning(
            f"Pominięte zatwierdzone przypadki: {summary.skipped_count}. Ich zapisy są niespójne, "
            "więc nie trafią do pliku."
        )
    if summary.exceeds_limit:
        st.error(
            f"Za dużo przypadków na jeden plik (limit: {summary.max_export_cases}). "
            "Zawęź zakres dat zatwierdzenia."
        )
    elif summary.eligible_count == 0:
        st.info("Nie ma jeszcze zatwierdzonych przypadków do eksportu. Zatwierdź przypadek na ekranie szczegółów.")

    if st.button(
        "Wygeneruj plik Excel",
        key="export_generate",
        type="primary",
        disabled=summary.eligible_count == 0 or summary.exceeds_limit,
    ):
        _generate(client, approved_from, approved_to)

    error = ss.get("x_error")
    if error:
        getattr(st, error[0])(error[1])

    result = ss.get("x_result")
    if result:
        if result["filters"] != (approved_from, approved_to):
            st.info("Zmieniono zakres dat. Wygeneruj plik ponownie, aby dopasować go do filtra.")
        else:
            file = result["file"]
            stamp = result["generated_at"].strftime("%H:%M:%S")
            st.success(f"Plik jest gotowy: {cases_pl(file.case_count)} (wygenerowano o {stamp}).")
            if file.case_count != summary.eligible_count:
                st.warning(
                    f"Od wygenerowania zmieniła się liczba zatwierdzonych przypadków (teraz: "
                    f"{summary.eligible_count}). Wygeneruj plik ponownie, aby był aktualny."
                )
            st.download_button(
                "Pobierz plik Excel (.xlsx)",
                data=file.content,
                file_name=file.filename,
                mime=XLSX_MIME,
                key="export_download",
                on_click="ignore",  # the download must not rerun the script or call the API again
            )
            st.caption(f"Nazwa pliku: {esc(file.filename)}. Serwer wygenerował plik; to, czy został zapisany na dysku, zależy od przeglądarki.")

    with st.expander("Jak czytać plik"):
        st.markdown(
            "- Arkusz **Zatwierdzone przypadki**: jeden wiersz na przypadek; brak wartości = pusta komórka.\n"
            "- Wartość oznaczona `[niepotwierdzone]` (żółte tło) była niejednoznaczna w analizie i nie "
            "została potwierdzona przez człowieka: nie traktuj jej jako ustalonego faktu.\n"
            "- **Zatwierdzono mimo problemów = TAK** oznacza zatwierdzenie z pisemnym uzasadnieniem "
            "(osobne kolumny pokazują uzasadnienie i problemy).\n"
            "- Teksty z e-maili są zapisane jako tekst: wartość zaczynająca się od `=`, `+`, `-` lub `@` "
            "dostaje na początku apostrof i nie zadziała jako formuła.\n"
            "- Daty i godziny są w UTC. Arkusz **Informacje** opisuje zakres i kryteria eksportu."
        )
